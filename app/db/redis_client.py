import json
import logging
from collections.abc import AsyncGenerator, Generator
from typing import Annotated, Any
import redis
import redis.asyncio as aioredis
from fastapi import Depends
from app.core.config import settings

logger = logging.getLogger(__name__)


# Sync Redis pool  (used by services that don't need async)

_sync_pool: redis.ConnectionPool | None = None


def get_sync_pool() -> redis.ConnectionPool:
    global _sync_pool
    if _sync_pool is None:
        _sync_pool = redis.ConnectionPool.from_url(
            settings.REDIS_URL,
            max_connections=settings.REDIS_MAX_CONNECTIONS,
            decode_responses=True,
        )
    return _sync_pool


def get_redis() -> Generator[redis.Redis, None, None]:
    client = redis.Redis(connection_pool=get_sync_pool())
    try:
        yield client
    finally:
        client.close()

RedisDep = Annotated[redis.Redis, Depends(get_redis)]


# Async Redis pool  (used in async endpoints / background tasks)

_async_pool: aioredis.ConnectionPool | None = None


def get_async_pool() -> aioredis.ConnectionPool:
    global _async_pool
    if _async_pool is None:
        _async_pool = aioredis.ConnectionPool.from_url(
            settings.REDIS_URL,
            max_connections=settings.REDIS_MAX_CONNECTIONS,
            decode_responses=True,
        )
    return _async_pool


async def get_async_redis() -> AsyncGenerator[aioredis.Redis, None]:
    client = aioredis.Redis(connection_pool=get_async_pool())
    try:
        yield client
    finally:
        await client.aclose()


AsyncRedisDep = Annotated[aioredis.Redis, Depends(get_async_redis)]

def ping_redis() -> bool:
    """Returns True if Redis is reachable. Used in /health endpoint."""
    try:
        client = redis.Redis(connection_pool=get_sync_pool())
        return client.ping()
    except redis.RedisError as exc:
        logger.warning("Redis health check failed: %s", exc)
        return False



# High-level cache helpers
# Used by services to avoid repeating get/set boilerplate.

class RedisCache:

    def __init__(self, client: redis.Redis, prefix: str = "career_ai") -> None:
        self._client = client
        self._prefix = prefix

    def _key(self, key: str) -> str:
        return f"{self._prefix}:{key}"

    def get(self, key: str) -> Any | None:
        try:
            raw = self._client.get(self._key(key))
            if raw is None:
                return None
            return json.loads(raw)
        except (redis.RedisError, json.JSONDecodeError) as exc:
            logger.warning("Cache GET failed for key '%s': %s", key, exc)
            return None

    def set(self, key: str, value: Any, ttl: int | None = None) -> bool:
        try:
            serialised = json.dumps(value, default=str)
            if ttl:
                self._client.setex(self._key(key), ttl, serialised)
            else:
                self._client.set(self._key(key), serialised)
            return True
        except (redis.RedisError, TypeError) as exc:
            logger.warning("Cache SET failed for key '%s': %s", key, exc)
            return False

    def delete(self, key: str) -> bool:
        try:
            self._client.delete(self._key(key))
            return True
        except redis.RedisError as exc:
            logger.warning("Cache DELETE failed for key '%s': %s", key, exc)
            return False

    def exists(self, key: str) -> bool:
        try:
            return bool(self._client.exists(self._key(key)))
        except redis.RedisError:
            return False

    def set_add(self, key: str, *values: str) -> bool:
        """Add values to a Redis set (used for token blacklisting)."""
        try:
            self._client.sadd(self._key(key), *values)
            return True
        except redis.RedisError as exc:
            logger.warning("Cache SADD failed for key '%s': %s", key, exc)
            return False

    def set_is_member(self, key: str, value: str) -> bool:
        """Check if value is in a Redis set (used for token blacklist lookup)."""
        try:
            return bool(self._client.sismember(self._key(key), value))
        except redis.RedisError:
            return False

    def increment(self, key: str, amount: int = 1, ttl: int | None = None) -> int | None:
        """Atomic increment — used for streak counters and rate limiting."""
        try:
            full_key = self._key(key)
            result = self._client.incrby(full_key, amount)
            if ttl and result == amount:
                # Only set expiry on first creation
                self._client.expire(full_key, ttl)
            return result
        except redis.RedisError as exc:
            logger.warning("Cache INCR failed for key '%s': %s", key, exc)
            return None



# Cache key constants
# Centralise all key patterns here so they're easy to find and refactor.

class CacheKeys:
    # Roadmap generated by AI — long TTL, re-generate weekly
    ROADMAP = "roadmap:{faculty}:{dept}:{role}"          # TTL: 24h
    # Syllabus generated by AI
    SYLLABUS = "syllabus:{role}:{depth}"                  # TTL: 24h
    # BD market data per career role
    BD_MARKET = "bd_market:{role}"                        # TTL: 7 days
    # User dashboard stats (XP, level, streak)
    USER_STATS = "user_stats:{user_id}"                   # TTL: 60s
    # Blacklisted JWT tokens (logout)
    TOKEN_BLACKLIST = "token_blacklist"                    # Redis set, no TTL
    # Rate limiting buckets
    RATE_LIMIT = "rate:{ip}:{endpoint}"                   # TTL: 60s

    @staticmethod
    def roadmap(faculty: str, dept: str, role: str) -> str:
        return CacheKeys.ROADMAP.format(faculty=faculty, dept=dept, role=role)

    @staticmethod
    def syllabus(role: str, depth: int) -> str:
        return CacheKeys.SYLLABUS.format(role=role, depth=depth)

    @staticmethod
    def bd_market(role: str) -> str:
        return CacheKeys.BD_MARKET.format(role=role)

    @staticmethod
    def user_stats(user_id: str) -> str:
        return CacheKeys.USER_STATS.format(user_id=user_id)